"""Unbiased learning to rank from simulated clicks on MSLR-WEB10K (fold 1).

Protocol (Joachims et al., 2017; Ai et al., 2018): a production LambdaMART trained on 60 random
training queries (30 trees) ranks every training query; simulated users see the top 10 and click
under the position-based model with examination (1/rank)^eta and click noise 0.1; 10 percent of
sessions carry a swap intervention. From 2,000,000 sessions we fit click models and train
LambdaMART (squared-error objective, 300 trees, learning rate 0.05) on the shown documents with:

* naive targets (click-through rate),
* IPW targets with the true propensities,
* IPW targets with propensities estimated by the swap intervention,
* IPW targets with propensities estimated by EM under the PBM,
* the true attractiveness of the same shown documents (the full-information skyline).

Everything is evaluated on the fold 1 test queries with the true labels. Seeds 0, 1, 2 change
the production queries, the sessions and the trees' row order; we report mean and standard
deviation. A second table fits PBM, cascade and CTR-by-rank click models to clicks generated by
PBM and by cascade users and reports held-out log-likelihood and perplexity.

    uv run python benchmarks/ultr_mslr.py

Results: benchmarks/results/ultr_mslr.json
"""

from __future__ import annotations

import sys
from typing import Any

import numpy as np
from common import MSLR, Timer, machine, peak_rss_mb, write

SESSIONS = 2_000_000
SEEDS = (0, 1, 2)
ETAS = (1.0, 2.0)


def main() -> None:
    from learning_to_rank import LambdaMART
    from learning_to_rank.clicks import (
        ClickConfig,
        attractiveness,
        fit_cascade,
        fit_ctr,
        fit_pbm,
        pbm_propensity,
        simulate_clicks,
        swap_propensity,
    )
    from learning_to_rank.datasets import load_mslr_fold
    from learning_to_rank.metrics import evaluate
    from learning_to_rank.unbiased import click_training_data, shown_with_true_labels

    sessions = int(sys.argv[1]) if len(sys.argv) > 1 else SESSIONS
    train, _, test = load_mslr_fold(MSLR, 1)
    learner = {"objective": "regression", "n_estimators": 300, "learning_rate": 0.05}
    runs: list[dict[str, Any]] = []
    propensities: dict[str, Any] = {}
    for eta in ETAS:
        for seed in SEEDS:
            rng = np.random.default_rng(seed)
            few = train.subset(rng.choice(train.n_queries, 60, replace=False))
            production = LambdaMART(n_estimators=30, seed=seed).fit(few)
            prod_scores = production.predict(train)
            cfg = ClickConfig(model="pbm", eta=eta, swap_fraction=0.1)
            with Timer() as ts:
                log = simulate_clicks(train, prod_scores, sessions, cfg, seed=seed)
            with Timer() as te:
                pbm = fit_pbm(log, train.n_docs)
            swap = swap_propensity(log)
            props = {
                "naive": None,
                "ipw_true": pbm_propensity(10, eta),
                "ipw_swap": np.maximum(swap, 1e-3),
                "ipw_em": pbm.relative_theta(),
            }
            if seed == 0:
                propensities[f"eta={eta:g}"] = {
                    "true": pbm_propensity(10, eta).tolist(),
                    "swap": swap.tolist(),
                    "em": pbm.relative_theta().tolist(),
                    "em_iterations": pbm.iterations,
                }
            row: dict[str, Any] = {
                "eta": eta,
                "seed": seed,
                "sessions": log.n_sessions,
                "clicks": int(log.clicks.sum()),
                "simulate_seconds": ts.seconds,
                "em_seconds": te.seconds,
                "production": evaluate(test, production.predict(test)),
            }
            for name, prop in props.items():
                data = click_training_data(train, log, prop)
                model = LambdaMART(seed=seed, **learner).fit(data)  # type: ignore[arg-type]
                row[name] = evaluate(test, model.predict(test))
                row["shown_docs"] = data.n_docs
            shown = shown_with_true_labels(train, log)
            sky = shown.with_labels(attractiveness(shown.y, cfg.epsilon, cfg.max_grade))
            row["skyline"] = evaluate(test, LambdaMART(seed=seed, **learner).fit(sky).predict(test))  # type: ignore[arg-type]
            runs.append(row)
            print(
                f"eta {eta:g} seed {seed}: "
                + "  ".join(
                    f"{k} {row[k]['ndcg@10']:.4f}" for k in ("production", *props, "skyline")
                ),
                flush=True,
            )
    full = LambdaMART(n_estimators=500).fit(train)
    supervised = evaluate(test, full.predict(test))

    click_models: dict[str, Any] = {}
    rng = np.random.default_rng(0)
    production = LambdaMART(n_estimators=30).fit(
        train.subset(rng.choice(train.n_queries, 60, replace=False))
    )
    prod_scores = production.predict(train)
    for user in ("pbm", "cascade"):
        log = simulate_clicks(
            train, prod_scores, sessions, ClickConfig(model=user, swap_fraction=0.1), seed=7
        )
        fit, held = log.split(0.8, seed=0)
        click_models[user] = {
            m.name: m.evaluate(held)
            for m in (
                fit_pbm(fit, train.n_docs),
                fit_cascade(fit, train.n_docs),
                fit_ctr(fit, train.n_docs),
            )
        }
        print(
            user, {k: round(v["perplexity"], 4) for k, v in click_models[user].items()}, flush=True
        )

    write(
        "ultr_mslr.json",
        {
            "protocol": {
                "fold": 1,
                "sessions": sessions,
                "top_k": 10,
                "epsilon": 0.1,
                "swap_fraction": 0.1,
                "production": "LambdaMART, 30 trees, 60 random training queries",
                "learner": learner,
                "seeds": list(SEEDS),
                "etas": list(ETAS),
            },
            "runs": runs,
            "supervised_full_labels": supervised,
            "propensities": propensities,
            "click_models": click_models,
            "peak_rss_mb": peak_rss_mb(),
            "machine": machine(),
        },
    )


if __name__ == "__main__":
    main()
